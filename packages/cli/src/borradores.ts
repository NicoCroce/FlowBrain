import { readdir, readFile, realpath, rm, stat } from "node:fs/promises";
import { join, resolve, sep } from "node:path";
import { cmp, ConsultaError, MARCA_FIN, MARCA_INICIO, type Cerebro } from "@flowbrain/core";
import { borradoresPromovibles, promover, type Candidato, type ResultadoPromover } from "./promover.js";

/**
 * La pantalla Borradores del visor (dec. 234): lo que el agente (o `flowbrain draft`) dejó en `_drafts/` para que una
 * persona lo revise. Lista, muestra qué cambia frente a la página actual, promueve (con la MISMA lógica de
 * `flowbrain promote`: si el cerebro deja de compilar, se deshace todo) y descarta. Todo dentro de `_drafts/`: una
 * ruta que se sale (`..`, absoluta, un enlace simbólico) no pasa.
 */

/** Qué es un borrador, para filtrar: una funcionalidad, sus especificaciones, una librería, otra pieza técnica o una nota. */
export type ClaseDeBorrador = "funcionalidad" | "especificaciones" | "libreria" | "tecnologia" | "nota";

export interface BorradorListado {
  cerebro: string;
  /** Ruta dentro del cerebro: `_drafts/product/feat-x.md`, `_drafts/<repo>/technology/lib-x.md`, `_drafts/notes/x.md`. */
  origen: string;
  id: string;
  /** Dónde queda al aceptarlo; null en una nota (no se promueve: se resuelve o se descarta). */
  destino: string | null;
  estado: Candidato["estado"] | "nota";
  clase: ClaseDeBorrador;
  /** El repo del que salió (`_drafts/<repo>/…`), si es de uno. */
  repo: string | null;
  nombre: string | null;
  /** Última modificación (ms): el visor marca los que dejó un lote recién terminado. */
  modificado: number;
}

/** Una línea de un diff: igual, quitada o agregada. */
export type LineaDeDiff = ["=" | "-" | "+", string];

export interface CambioDeBorrador {
  /** `campo` del frontmatter (`nombre`, `especificaciones`) o `seccion` del cuerpo (el título `## …`, o "" antes del primero). */
  donde: "campo" | "seccion";
  nombre: string;
  cambio: "nuevo" | "quitado" | "cambiado";
  lineas: LineaDeDiff[];
}

export interface DiffDeBorrador extends BorradorListado {
  borrador: string;
  /** La página actual (o null si es nueva o es una nota). */
  actual: string | null;
  cambios: CambioDeBorrador[];
}

const CAMPOS_DE_ESPECIFICACIONES = new Set(["casos", "especificaciones"]);
const AVISO_DRAFT = /^> (?:Borrador generado por|Draft generated by) `flowbrain draft`[^\n]*\n\n?/m;
const leer = (p: string) => readFile(p, "utf8").catch(() => null);
const invalido = (m: string) => new ConsultaError("parametro_invalido", m);

/**
 * La ruta absoluta de un borrador del cerebro, o error si no es uno: tiene que ser un `.md` dentro de `_drafts/` (sin
 * `..`, sin ser absoluta, sin salir por un enlace simbólico) y existir.
 */
export async function rutaDeBorrador(raiz: string, origen: unknown): Promise<string> {
  if (typeof origen !== "string" || !/^_drafts\/[^\0]+\.md$/.test(origen) || origen.split("/").some((p) => p === ".." || p === "." || !p) || /\/PROMPT\.md$/.test(origen)) throw invalido(`not a draft: ${String(origen)}`);
  let base: string, destino: string;
  try {
    base = await realpath(join(raiz, "_drafts"));
    destino = await realpath(resolve(raiz, origen));
  } catch {
    throw new ConsultaError("nodo_inexistente", `no such draft: ${origen}`);
  }
  if (!destino.startsWith(base + sep)) throw invalido(`the path leaves _drafts/: ${origen}`);
  return destino;
}

/** Los bloques de primer nivel del frontmatter (`clave:` y sus líneas), con el texto tal como está escrito. */
function bloquesDelFrontmatter(texto: string): Map<string, string> {
  const out = new Map<string, string>();
  const m = /^---\n([\s\S]*?)\n---[ \t]*(?:\n|$)/.exec(texto.replace(/\r\n/g, "\n"));
  if (!m) return out;
  let actual: string | null = null, lineas: string[] = [];
  const cerrar = () => { if (actual !== null) out.set(actual, lineas.join("\n").replace(/\s+$/, "")); };
  for (const l of m[1]!.split("\n")) {
    const k = /^([A-Za-z_][\w-]*)\s*:/.exec(l);
    if (k) { cerrar(); actual = k[1]!; lineas = [l]; } else if (actual !== null) lineas.push(l);
  }
  cerrar();
  return out;
}

/**
 * Las secciones del cuerpo por su título `## …` ("" es lo de antes del primero), sin el aviso de `flowbrain draft` ni
 * los backlinks que agrega el compilador (se regeneran al compilar: no son un cambio del borrador).
 */
function seccionesDelCuerpo(texto: string): Map<string, string> {
  const t = texto.replace(/\r\n/g, "\n");
  const m = /^---\n[\s\S]*?\n---[ \t]*(?:\n|$)/.exec(t);
  let cuerpo = (m ? t.slice(m[0].length) : t).replace(AVISO_DRAFT, "");
  const i = cuerpo.indexOf(MARCA_INICIO), f = cuerpo.indexOf(MARCA_FIN);
  if (i >= 0 && f > i) cuerpo = cuerpo.slice(0, i) + cuerpo.slice(f + MARCA_FIN.length);
  const out = new Map<string, string>();
  let actual = "", lineas: string[] = [];
  const cerrar = () => { const v = lineas.join("\n").trim(); if (v || actual) out.set(actual, v); };
  for (const l of cuerpo.split("\n")) {
    const h = /^##\s+(.+?)\s*$/.exec(l);
    if (h) { cerrar(); actual = h[1]!; lineas = []; } else lineas.push(l);
  }
  cerrar();
  return out;
}

/** Diff por líneas (LCS), suficiente para una página: unas cientos de líneas. Más grande, quitado todo y agregado todo. */
export function diffDeLineas(a: string, b: string): LineaDeDiff[] {
  const x = a ? a.split("\n") : [], y = b ? b.split("\n") : [];
  if (x.length * y.length > 400_000) return [...x.map((l): LineaDeDiff => ["-", l]), ...y.map((l): LineaDeDiff => ["+", l])];
  const n = x.length, m = y.length, t: number[][] = Array.from({ length: n + 1 }, () => new Array<number>(m + 1).fill(0));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) t[i]![j] = x[i] === y[j] ? t[i + 1]![j + 1]! + 1 : Math.max(t[i + 1]![j]!, t[i]![j + 1]!);
  const out: LineaDeDiff[] = [];
  let i = 0, j = 0;
  while (i < n && j < m) {
    if (x[i] === y[j]) { out.push(["=", x[i]!]); i++; j++; } else if (t[i + 1]![j]! >= t[i]![j + 1]!) out.push(["-", x[i++]!]); else out.push(["+", y[j++]!]);
  }
  while (i < n) out.push(["-", x[i++]!]);
  while (j < m) out.push(["+", y[j++]!]);
  return out;
}

/** Qué cambia entre la página actual y el borrador, campo por campo del frontmatter y sección por sección del cuerpo. */
export function cambiosDeBorrador(actual: string | null, borrador: string): CambioDeBorrador[] {
  const out: CambioDeBorrador[] = [];
  const comparar = (donde: CambioDeBorrador["donde"], a: Map<string, string>, b: Map<string, string>) => {
    for (const k of new Set([...a.keys(), ...b.keys()])) {
      const va = a.get(k), vb = b.get(k);
      if (va === vb) continue;
      out.push({ donde, nombre: k, cambio: va === undefined ? "nuevo" : vb === undefined ? "quitado" : "cambiado", lineas: diffDeLineas(va ?? "", vb ?? "") });
    }
  };
  comparar("campo", actual === null ? new Map() : bloquesDelFrontmatter(actual), bloquesDelFrontmatter(borrador));
  comparar("seccion", actual === null ? new Map() : seccionesDelCuerpo(actual), seccionesDelCuerpo(borrador));
  return out;
}

const valorDe = (texto: string, campo: string) => {
  const b = bloquesDelFrontmatter(texto).get(campo);
  const v = b ? b.slice(b.indexOf(":") + 1).trim().replace(/^["']|["']$/g, "") : "";
  return v || null;
};

function claseDe(c: Candidato, texto: string, actual: string | null): ClaseDeBorrador {
  if (c.destino.startsWith("technology/")) return c.id.startsWith("lib-") || valorDe(texto, "tipo") === "lib" ? "libreria" : "tecnologia";
  // Una funcionalidad que ya existe y solo cambia en sus casos y especificaciones es un borrador de especificaciones.
  if (actual !== null) {
    const cs = cambiosDeBorrador(actual, texto);
    if (cs.length && cs.every((x) => x.donde === "campo" && CAMPOS_DE_ESPECIFICACIONES.has(x.nombre))) return "especificaciones";
  }
  return "funcionalidad";
}

/** Los borradores de un cerebro: los que se promueven (los mismos que `flowbrain promote`) y las notas. */
export async function listarBorradores(c: Pick<Cerebro, "nombre" | "raiz">): Promise<BorradorListado[]> {
  const out: BorradorListado[] = [];
  const cuando = (p: string) => stat(join(c.raiz, p)).then((s) => s.mtimeMs, () => 0);
  for (const x of await borradoresPromovibles(c.raiz)) {
    const texto = (await leer(join(c.raiz, x.origen))) ?? "", actual = x.estado === "nuevo" ? null : await leer(join(c.raiz, x.destino));
    const repo = /^_drafts\/([^/]+)\/(?:technology|product)\//.exec(x.origen)?.[1] ?? null;
    out.push({ cerebro: c.nombre, origen: x.origen, id: x.id, destino: x.destino, estado: x.estado, clase: claseDe(x, texto, actual), repo, nombre: valorDe(texto, "nombre"), modificado: await cuando(x.origen) });
  }
  for (const n of (await readdir(join(c.raiz, "_drafts", "notes")).catch(() => [] as string[])).filter((x) => x.endsWith(".md")).sort(cmp)) {
    const origen = `_drafts/notes/${n}`;
    out.push({ cerebro: c.nombre, origen, id: n.slice(0, -3), destino: null, estado: "nota", clase: "nota", repo: null, nombre: null, modificado: await cuando(origen) });
  }
  return out;
}

/** Un borrador con lo que cambia frente a su página (una nota: su texto, todo como agregado). */
export async function diffDeBorrador(c: Pick<Cerebro, "nombre" | "raiz">, origen: unknown): Promise<DiffDeBorrador> {
  const ruta = await rutaDeBorrador(c.raiz, origen);
  const x = (await listarBorradores(c)).find((b) => b.origen === origen);
  if (!x) throw new ConsultaError("nodo_inexistente", `no such draft: ${String(origen)}`);
  const borrador = (await readFile(ruta, "utf8")).replace(/\r\n/g, "\n");
  if (x.clase === "nota") return { ...x, borrador, actual: null, cambios: [{ donde: "seccion", nombre: "", cambio: "nuevo", lineas: diffDeLineas("", borrador.trim()) }] };
  const actual = x.destino && x.estado !== "nuevo" ? await leer(join(c.raiz, x.destino)) : null;
  return { ...x, borrador, actual, cambios: cambiosDeBorrador(actual, borrador) };
}

/**
 * Acepta borradores: `promover` de `flowbrain promote`, con `--write` y `--overwrite` (quien acepta ya vio el diff
 * contra la página). Si el cerebro deja de compilar, `promover` deshace todo y devuelve los errores. Las notas no se
 * promueven: se resuelven o se descartan.
 */
export async function aceptarBorradores(c: Pick<Cerebro, "raiz">, origenes: unknown): Promise<ResultadoPromover> {
  if (!Array.isArray(origenes) || !origenes.length || origenes.length > 3000) throw invalido("origenes must be a list of 1 to 3000 drafts");
  for (const o of origenes) {
    await rutaDeBorrador(c.raiz, o);
    if (String(o).startsWith("_drafts/notes/")) throw invalido(`a note is not promoted: resolve it or discard it (${String(o)})`);
  }
  return promover(c.raiz, { ids: origenes as string[], escribir: true, pisar: true });
}

/** Descarta un borrador (o una nota): lo borra de `_drafts/`. No se deshace. */
export async function descartarBorrador(c: Pick<Cerebro, "raiz">, origen: unknown): Promise<{ descartado: string }> {
  const ruta = await rutaDeBorrador(c.raiz, origen);
  await rm(ruta);
  return { descartado: origen as string };
}

/**
 * Si el agente ya revisó un borrador que se le devolvió (pedido «borrador»): cambió desde `desde`. Una nota resuelta
 * también puede ya no estar (el agente la borra al pasar su arreglo a un borrador).
 */
export async function borradorRevisado(raiz: string, origen: string, desde: number): Promise<boolean> {
  try {
    return (await stat(join(raiz, origen))).mtimeMs >= desde;
  } catch {
    return origen.startsWith("_drafts/notes/");
  }
}
