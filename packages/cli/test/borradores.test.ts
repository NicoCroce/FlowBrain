import { cp, mkdir, mkdtemp, readFile, rm, stat, symlink, utimes, writeFile } from "node:fs/promises";
import { request } from "node:http";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { leerRegistro } from "@flowbrain/core";
import { crearAgente, pedidoDeTandaPaginas, permisosDelPedido, indicacionesDelPedido } from "../src/agente.js";
import { borradorRevisado, cambiosDeBorrador, diffDeLineas, listarBorradores, rutaDeBorrador } from "../src/borradores.js";
import { crearServidorVisor, type ServidorVisor } from "../src/servidor-visor.js";

/**
 * Pantalla Borradores (dec. 234): un cerebro (la fixture checkout) con borradores de cada clase. Se listan, se ve qué
 * cambian frente a su página, se aceptan con la lógica de `flowbrain promote` (lo que rompe la compilación se deshace)
 * y se descartan, siempre dentro de `_drafts/`.
 */
const F = (p: string) => resolve(dirname(fileURLToPath(import.meta.url)), "../../../fixtures", p);
let dir: string, reg: string, raiz: string, s: ServidorVisor;
const pagina = (id: string, tipo: string, extra: string[] = [], cuerpo = `# ${id}`) => ["---", `id: ${id}`, `tipo: ${tipo}`, `nombre: ${id}`, `resumen: ${id}.`, ...extra, "---", cuerpo, ""].join("\n");
const escribir = async (ruta: string, contenido: string) => {
  await mkdir(dirname(join(raiz, ruta)), { recursive: true });
  await writeFile(join(raiz, ruta), contenido);
};
const existe = (p: string) => stat(join(raiz, p)).then(() => true, () => false);
let checkout: string;

interface Respuesta { estado: number; json: Record<string, unknown> }
function pedir(metodo: string, ruta: string, cuerpo?: unknown): Promise<Respuesta> {
  const puerto = (s.server.address() as { port: number }).port;
  const datos = cuerpo === undefined ? null : JSON.stringify(cuerpo);
  return new Promise((ok, mal) => {
    const req = request({ host: "127.0.0.1", port: puerto, method: metodo, path: ruta, headers: { host: `127.0.0.1:${puerto}`, "x-flowbrain-token": s.token, ...(datos !== null ? { "content-type": "application/json" } : {}) } }, (res) => {
      let t = "";
      res.setEncoding("utf8");
      res.on("data", (c: string) => (t += c));
      res.on("end", () => ok({ estado: res.statusCode ?? 0, json: JSON.parse(t || "{}") as Record<string, unknown> }));
    });
    req.on("error", mal);
    req.end(datos ?? undefined);
  });
}

beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), "brain-borradores-"));
  reg = join(dir, "registro");
  raiz = join(reg, "tienda");
  for (const d of ["product", "technology", "_build"]) await cp(F(`checkout/${d}`), join(raiz, d), { recursive: true });
  await writeFile(join(reg, "flowbrain.yaml"), ["version: 1", "cerebros:", "  - nombre: tienda", "    repos: []", ""].join("\n"));
  checkout = await readFile(join(raiz, "product/feat-checkout.md"), "utf8");
  // Una funcionalidad nueva, un cambio de descripción, uno solo de especificaciones, una librería, otra pieza, una que no compila y una nota.
  await escribir("_drafts/product/feat-avisos.md", pagina("feat-avisos", "feat"));
  await escribir("_drafts/repo-tienda/technology/lib-ui.md", pagina("lib-ui", "lib"));
  await escribir("_drafts/repo-tienda/technology/ext-correo.md", pagina("ext-correo", "ext"));
  await escribir("_drafts/repo-tienda/technology/svc-roto.md", pagina("svc-roto", "svc", ["vive_en: [repo-que-no-existe]"]));
  await escribir("_drafts/notes/tabla-pagos.md", "- la columna estado ahora admite reembolsado (manual)\n");
  await escribir("_drafts/repo-tienda/PROMPT.md", "no es una página\n");
  s = crearServidorVisor(reg, { agente: crearAgente(() => leerRegistro(reg), { comando: join(dir, "sin-claude") }) });
  await new Promise<void>((ok) => s.server.listen(0, "127.0.0.1", ok));
}, 60_000);
afterAll(async () => {
  await new Promise<void>((ok) => s.server.close(() => ok()));
  await rm(dir, { recursive: true, force: true });
});

describe("qué cambia un borrador", () => {
  it("diff por líneas: lo igual, lo quitado y lo agregado, en orden", () => {
    expect(diffDeLineas("a\nb\nc", "a\nx\nc")).toEqual([["=", "a"], ["-", "b"], ["+", "x"], ["=", "c"]]);
    expect(diffDeLineas("", "a")).toEqual([["+", "a"]]);
  });
  it("compara campo por campo del frontmatter y sección por sección del cuerpo, sin el aviso de flowbrain draft", () => {
    const antes = ["---", "id: feat-a", "tipo: feat", "nombre: A", "resumen: Viejo.", "---", "# A", "", "## Qué es", "Algo.", ""].join("\n");
    const despues = ["---", "id: feat-a", "tipo: feat", "nombre: A", "resumen: Nuevo.", "aliases: [b]", "---", "> Draft generated by `flowbrain draft` from x.", "", "# A", "", "## Qué es", "Algo.", "", "## Preguntas abiertas", "- ¿Quién?", ""].join("\n");
    const cs = cambiosDeBorrador(antes, despues);
    expect(cs.map((c) => [c.donde, c.nombre, c.cambio])).toEqual([["campo", "resumen", "cambiado"], ["campo", "aliases", "nuevo"], ["seccion", "Preguntas abiertas", "nuevo"]]);
    expect(cs[0]!.lineas).toEqual([["-", "resumen: Viejo."], ["+", "resumen: Nuevo."]]);
    // Los backlinks los regenera el compilador: que la página los tenga y el borrador no, no es un cambio.
    const conBacklinks = antes + "\n<!-- brain:backlinks:inicio -->\n## Backlinks\n\n- [[svc-web]] · implementa\n<!-- brain:backlinks:fin -->\n";
    expect(cambiosDeBorrador(conBacklinks, antes)).toEqual([]);
  });
});

describe("la guardia de _drafts/", () => {
  it("acepta un borrador o una nota, y nada fuera de _drafts/ (.., otra carpeta, PROMPT.md, un enlace que se sale)", async () => {
    expect(await rutaDeBorrador(raiz, "_drafts/product/feat-avisos.md")).toMatch(/feat-avisos\.md$/);
    expect(await rutaDeBorrador(raiz, "_drafts/notes/tabla-pagos.md")).toMatch(/tabla-pagos\.md$/);
    for (const mala of ["product/feat-checkout.md", "_drafts/../product/feat-checkout.md", "/etc/passwd", "_drafts/repo-tienda/PROMPT.md", "_drafts/product/no-existe.md", "_drafts//x.md", 3])
      await expect(rutaDeBorrador(raiz, mala)).rejects.toThrow();
    await symlink(join(raiz, "product"), join(raiz, "_drafts/afuera"));
    await expect(rutaDeBorrador(raiz, "_drafts/afuera/feat-checkout.md")).rejects.toThrow(/leaves _drafts/);
    await rm(join(raiz, "_drafts/afuera"));
  });
});

describe("listar borradores", () => {
  it("cada uno con su clase: funcionalidad, especificaciones, librería, otra pieza técnica o nota", async () => {
    await escribir("_drafts/product/feat-checkout.md", checkout.replace(/^---\n([\s\S]*?)\n---/, (_m, fm: string) => `---\n${fm}\nespecificaciones:\n  - id: tarjeta-vencida\n    texto: No se puede pagar con una tarjeta vencida.\n    tipo: negocio\n---`));
    const xs = await listarBorradores({ nombre: "tienda", raiz });
    expect(xs.map((x) => [x.origen, x.clase, x.estado, x.destino])).toEqual([
      ["_drafts/product/feat-avisos.md", "funcionalidad", "nuevo", "product/feat-avisos.md"],
      ["_drafts/product/feat-checkout.md", "especificaciones", "distinto", "product/feat-checkout.md"],
      ["_drafts/repo-tienda/technology/ext-correo.md", "tecnologia", "nuevo", "technology/ext-correo.md"],
      ["_drafts/repo-tienda/technology/lib-ui.md", "libreria", "nuevo", "technology/lib-ui.md"],
      ["_drafts/repo-tienda/technology/svc-roto.md", "tecnologia", "nuevo", "technology/svc-roto.md"],
      ["_drafts/notes/tabla-pagos.md", "nota", "nota", null],
    ]);
    expect(xs.find((x) => x.id === "lib-ui")).toMatchObject({ repo: "repo-tienda", nombre: "lib-ui", cerebro: "tienda" });
    // Si además cambia la descripción, ya no es solo de especificaciones.
    await escribir("_drafts/product/feat-checkout.md", checkout.replace(/^resumen: .*$/m, "resumen: El cliente paga el carrito."));
    expect((await listarBorradores({ nombre: "tienda", raiz })).find((x) => x.id === "feat-checkout")?.clase).toBe("funcionalidad");
  });
});

describe("el servidor del visor", () => {
  it("lista los borradores de todos los cerebros y muestra el diff de uno contra su página", async () => {
    const l = await pedir("GET", "/api/borradores");
    expect(l.estado).toBe(200);
    expect((l.json["borradores"] as Array<{ origen: string }>).map((x) => x.origen)).toContain("_drafts/notes/tabla-pagos.md");
    const d = await pedir("GET", "/api/borradores/diff?cerebro=tienda&origen=" + encodeURIComponent("_drafts/product/feat-checkout.md"));
    expect(d.estado).toBe(200);
    expect(d.json["actual"]).toBe(checkout);
    expect(d.json["cambios"]).toEqual([{ donde: "campo", nombre: "resumen", cambio: "cambiado", lineas: [["-", "resumen: El cliente confirma el carrito, paga con tarjeta y recibe el estado del pedido."], ["+", "resumen: El cliente paga el carrito."]] }]);
    const n = await pedir("GET", "/api/borradores/diff?cerebro=tienda&origen=" + encodeURIComponent("_drafts/notes/tabla-pagos.md"));
    expect(n.json).toMatchObject({ clase: "nota", actual: null, cambios: [{ cambio: "nuevo", lineas: [["+", "- la columna estado ahora admite reembolsado (manual)"]] }] });
    expect((await pedir("GET", "/api/borradores/diff?cerebro=tienda&origen=" + encodeURIComponent("product/feat-checkout.md"))).estado).toBe(400);
    expect((await pedir("GET", "/api/borradores/diff?cerebro=otro&origen=x")).estado).toBe(404);
  });

  it("aceptar pisa la página (ya se vio el diff) y compila; lo que no compila se deshace y vuelve el error", async () => {
    const ok = await pedir("POST", "/api/borradores/aceptar", { borradores: [{ cerebro: "tienda", origen: "_drafts/product/feat-checkout.md" }, { cerebro: "tienda", origen: "_drafts/repo-tienda/technology/lib-ui.md" }] });
    expect(ok.estado).toBe(200);
    expect(ok.json).toEqual({ cerebros: [{ cerebro: "tienda", movidos: ["_drafts/product/feat-checkout.md", "_drafts/repo-tienda/technology/lib-ui.md"], salteados: [], errores: [] }] });
    expect(await readFile(join(raiz, "product/feat-checkout.md"), "utf8")).toContain("resumen: El cliente paga el carrito.");
    expect(await existe("_drafts/product/feat-checkout.md")).toBe(false);
    expect(await readFile(join(raiz, "_build/graph.json"), "utf8")).toContain("lib-ui");

    const mal = await pedir("POST", "/api/borradores/aceptar", { borradores: [{ cerebro: "tienda", origen: "_drafts/repo-tienda/technology/ext-correo.md" }, { cerebro: "tienda", origen: "_drafts/repo-tienda/technology/svc-roto.md" }] });
    const r = (mal.json["cerebros"] as Array<{ movidos: string[]; errores: string[] }>)[0]!;
    expect(r.movidos).toEqual([]);
    expect(r.errores.join("\n")).toContain("technology/svc-roto.md");
    expect(await existe("_drafts/repo-tienda/technology/ext-correo.md")).toBe(true);
    expect(await existe("technology/ext-correo.md")).toBe(false);
  }, 60_000);

  it("una nota no se acepta; descartar la borra, y nada fuera de _drafts/", async () => {
    expect((await pedir("POST", "/api/borradores/aceptar", { borradores: [{ cerebro: "tienda", origen: "_drafts/notes/tabla-pagos.md" }] })).estado).toBe(400);
    expect((await pedir("POST", "/api/borradores/aceptar", { borradores: [] })).estado).toBe(400);
    expect((await pedir("POST", "/api/borradores/descartar", { cerebro: "tienda", origen: "_drafts/../product/feat-checkout.md" })).estado).toBe(400);
    expect(await existe("product/feat-checkout.md")).toBe(true);
    const d = await pedir("POST", "/api/borradores/descartar", { cerebro: "tienda", origen: "_drafts/repo-tienda/technology/svc-roto.md" });
    expect(d).toEqual({ estado: 200, json: { descartado: "_drafts/repo-tienda/technology/svc-roto.md" } });
    expect(await existe("_drafts/repo-tienda/technology/svc-roto.md")).toBe(false);
    expect((await pedir("POST", "/api/borradores/descartar", { cerebro: "tienda", origen: "_drafts/repo-tienda/technology/svc-roto.md" })).estado).toBe(404);
  });

  it("«Pedir corrección» va en un lote «borrador»: valida la ruta del borrador antes de pedirle al agente", async () => {
    const item = { cerebro: "tienda", funcionalidad: "feat-avisos", borrador: "_drafts/product/feat-avisos.md", linea: "- tienda · _drafts/product/feat-avisos.md · note: name it Notifications" };
    expect((await pedir("POST", "/api/agente/lote", { tipo: "borrador", items: [{ ...item, borrador: "product/feat-checkout.md" }] })).estado).toBe(400);
    expect((await pedir("POST", "/api/agente/lote", { tipo: "borrador", items: [{ ...item, borrador: undefined }] })).estado).toBe(400);
    expect((await pedir("POST", "/api/agente/lote", { tipo: "escribir", items: [{ cerebro: "tienda", funcionalidad: "feat-avisos", borrador: "_drafts/product/feat-avisos.md", linea: "x" }] })).estado).toBe(400);
    // Bien armado: llega hasta el agente, que en esta máquina de prueba no está.
    expect((await pedir("POST", "/api/agente/lote", { tipo: "borrador", items: [item] })).estado).toBe(409);
  });
});

describe("el pedido «borrador» al agente", () => {
  it("escribe solo en _drafts/ de sus cerebros, sin promover, con su guía", () => {
    const p = permisosDelPedido("borrador", ["/r/tienda"]);
    expect(p.escritura).toEqual(["/r/tienda/_drafts/**"]);
    expect(p.comandos).not.toContain("flowbrain promote");
    expect(p.comandos).not.toContain("flowbrain draft");
    const t = pedidoDeTandaPaginas("borrador", [{ cerebro: "tienda", funcionalidad: "feat-avisos", borrador: "_drafts/product/feat-avisos.md", linea: "- tienda · _drafts/product/feat-avisos.md · note: x" }], 1, 1);
    expect(t).toContain("Revise this FlowBrain draft");
    expect(t).toContain("write ONLY in .flowbrain/<brain>/_drafts/");
    expect(indicacionesDelPedido("borrador", t)).toContain("You are going to revise FlowBrain drafts");
  });
  it("resuelto es el borrador que cambió desde que empezó la tanda; una nota, también si ya no está", async () => {
    const desde = Date.now();
    await utimes(join(raiz, "_drafts/product/feat-avisos.md"), new Date(desde - 60_000), new Date(desde - 60_000));
    expect(await borradorRevisado(raiz, "_drafts/product/feat-avisos.md", desde)).toBe(false);
    await escribir("_drafts/product/feat-avisos.md", pagina("feat-avisos", "feat", [], "# Avisos"));
    expect(await borradorRevisado(raiz, "_drafts/product/feat-avisos.md", desde - 1000)).toBe(true);
    expect(await borradorRevisado(raiz, "_drafts/notes/ya-no-esta.md", desde)).toBe(true);
    expect(await borradorRevisado(raiz, "_drafts/product/ya-no-esta.md", desde)).toBe(false);
  });
});
